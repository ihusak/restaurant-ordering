import type { Category, Cents, MenuItem, Order } from './models';

/**
 * `epoch` identifies a server run. The server keeps data in memory, so after a
 * restart versions start over and clients must reload instead of replaying.
 */
export interface MenuSnapshot {
  epoch: string;
  version: number;
  categories: Category[];
  items: MenuItem[];
}

export interface OrdersSnapshot {
  epoch: string;
  version: number;
  orders: Order[];
}

export interface CategoryInput {
  name: string;
  sortOrder?: number;
}

export interface MenuItemInput {
  categoryId: string;
  name: string;
  description: string;
  openPrice: boolean;
  price: Cents | null;
  available: boolean;
}

export type MenuItemPatch = Partial<MenuItemInput>;
export type CategoryPatch = Partial<CategoryInput>;

export interface CreateOrderLine {
  itemId: string;
  /** What the client believed: lets the server detect an item switched between fixed and open price. */
  openPrice: boolean;
  quantity: number;
  /** For fixed-price items: the price the user saw. For open-price items: the price the user entered. */
  unitPrice: Cents;
}

export interface CreateOrderRequest {
  /** Generated by the client once per checkout attempt; retries reuse it. */
  idempotencyKey: string;
  lines: CreateOrderLine[];
  discount: Cents;
}

/** Why a cart line can no longer be ordered as it is. */
export type MenuIssue =
  | { itemId: string; kind: 'removed' }
  | { itemId: string; kind: 'unavailable' }
  | { itemId: string; kind: 'price_changed'; expected: Cents; actual: Cents }
  | { itemId: string; kind: 'pricing_changed'; openPrice: boolean };

export type ApiErrorCode =
  | 'VALIDATION'
  | 'NOT_FOUND'
  | 'MENU_CHANGED'
  | 'IDEMPOTENCY_MISMATCH'
  | 'CATEGORY_NOT_EMPTY'
  | 'UNAVAILABLE'
  | 'INTERNAL';

export interface ApiErrorBody {
  code: ApiErrorCode;
  message: string;
  issues?: MenuIssue[];
}
